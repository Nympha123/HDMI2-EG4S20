function [1:0] first_slot_ok;
    input [3:0] mask;
    begin
        if (mask[0])      first_slot_ok = 2'd0;
        else if (mask[1]) first_slot_ok = 2'd1;
        else if (mask[2]) first_slot_ok = 2'd2;
        else              first_slot_ok = 2'd3;
    end
endfunction

function [1:0] next_slot_ok;
    input [1:0] cur;
    input [3:0] mask;
    reg [1:0]   s;
    integer     k;
    reg         found;
    begin
        found = 1'b0;
        s     = cur;
        next_slot_ok = cur;
        for (k = 0; k < 4; k = k + 1) begin
            s = s + 2'd1;                       // 2 ???????????????
            if (!found && mask[s]) begin
                next_slot_ok = s;
                found        = 1'b1;
            end
        end
    end
endfunction

function [1:0] prev_slot_ok;
    input [1:0] cur;
    input [3:0] mask;
    reg [1:0]   s;
    integer     k;
    reg         found;
    begin
        found = 1'b0;
        s     = cur;
        prev_slot_ok = cur;
        for (k = 0; k < 4; k = k + 1) begin
            s = s - 2'd1;                       // 2 ???????????????
            if (!found && mask[s]) begin
                prev_slot_ok = s;
                found        = 1'b1;
            end
        end
    end
endfunction

function [2:0] count_slots;
    input [3:0] mask;
    begin
        count_slots = {2'd0, mask[0]} + {2'd0, mask[1]} +
                      {2'd0, mask[2]} + {2'd0, mask[3]};
    end
endfunction

function [31:0] cluster_of;
