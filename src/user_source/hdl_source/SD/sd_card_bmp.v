function [2:0] next_preload;
    input [1:0] from;
    input [3:0] valid_mask;
    input [3:0] bad_mask;
    input [3:0] done_mask;
    integer   k;
    reg [1:0] c;
    begin
        next_preload = 3'd0;
        for (k = 0; k < 4; k = k + 1) begin
            c = from + k[1:0];
            if (!next_preload[2] && valid_mask[c] && !bad_mask[c] && !done_mask[c])
                next_preload = {1'b1, c};
        end
    end
endfunction

