                32'd15: hdr_dib_size[15:8]     <= streamer_byte;
                32'd16: hdr_dib_size[23:16]    <= streamer_byte;
                32'd17: hdr_dib_size[31:24]    <= streamer_byte;
                32'd18: hdr_width[7:0]         <= streamer_byte;
                32'd19: hdr_width[15:8]        <= streamer_byte;
                32'd20: hdr_width[23:16]       <= streamer_byte;
                32'd21: hdr_width[31:24]       <= streamer_byte;
                32'd22: hdr_height[7:0]        <= streamer_byte;
                32'd23: hdr_height[15:8]       <= streamer_byte;
                32'd24: hdr_height[23:16]      <= streamer_byte;
                32'd25: hdr_height[31:24]      <= streamer_byte;
                32'd26: hdr_planes[7:0]        <= streamer_byte;
                32'd27: hdr_planes[15:8]       <= streamer_byte;
                32'd28: hdr_bpp[7:0]           <= streamer_byte;
                32'd29: hdr_bpp[15:8]          <= streamer_byte;
                32'd30: hdr_compression[7:0]   <= streamer_byte;
                32'd31: hdr_compression[15:8]  <= streamer_byte;
                32'd32: hdr_compression[23:16] <= streamer_byte;
                32'd33: hdr_compression[31:24] <= streamer_byte;
                default: ;
            endcase
            // ?????? 34 ????????????????????????????????????????????????????????????
            if (streamer_byte_offset >= 32'd34)
                hdr_checked <= 1'b1;
            if (header_ok && hdr_checked &&
                (streamer_byte_offset + 32'd1 >= bmp_data_offset)) begin
                bmp_stream_state <= 2'd2;
                rgb_byte_count   <= 2'd0;
            end
        end else if (bmp_stream_state == 2'd2) begin
            case (rgb_byte_count)
                2'd0: begin
                    rgb_pixel[7:0]  <= streamer_byte;
                    rgb_byte_count   <= 2'd1;
                end
                2'd1: begin
                    rgb_pixel[15:8] <= streamer_byte;
                    rgb_byte_count   <= 2'd2;
                end
                default: begin
                    rgb_pixel[23:16] <= streamer_byte;
                    rgb_byte_count    <= 2'd0;
                end
            endcase
        end
    end
end

