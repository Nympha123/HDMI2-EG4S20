    if (!video_rst_n) begin
        wav_acc         <= 25'd0;
        wav_sample_tick <= 1'b0;
    end else if (wav_acc + 25'd48000 >= 25'd25000000) begin
        wav_acc         <= wav_acc + 25'd48000 - 25'd25000000;
        wav_sample_tick <= 1'b1;
    end else begin
        wav_acc         <= wav_acc + 25'd48000;
        wav_sample_tick <= 1'b0;
    end
end

