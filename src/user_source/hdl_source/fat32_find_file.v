// ????????????????????????????????????????????????????????????????????????????????????????????? LBA???
// ????????????"WAV ???????????????"???sd_card_bmp ??????????????????????????????????????????????????????
//       ??? LBA 0 ?????? BPB??????????????? MBR ??????????????????????????????????????????
//       ?????? 32 ???????????????**????????????????????????????????????**???v1 ???????????????????????????
//       ??????????????? first_cluster / file_size / data_start_lba / sectors_per_cluster???
//       ??????????????? start_lba ??? total_sectors???
//
// MATCH_MODE = 0????????????????????? WAV ?????????????????? 8.3 ???????????? 3 ?????????
// MATCH_MODE = 1????????? TARGET_NAME???11 ?????? 8.3 ???????????? "AUD1    WAV"???
//
// ???????????????????????????
//   - ??????????????? 512 ?????????????????? SD ????????????????????????
//   - ?????????????????????**??????**?????? MAX_ROOT_SECTORS ?????????????????? FAT ??????
//     ???TF ??????????????????????????????????????????????????????????????????????????????????????????
// ===========================================================================
module fat32_find_file #(
    parameter integer MATCH_MODE       = 0,
    parameter [87:0]  TARGET_NAME      = 88'h41554431_20202020_574156,  // "AUD1    WAV"?????????????????????
    parameter integer MAX_ROOT_SECTORS = 64
) (
    input  wire        clk,
    input  wire        rst_n,
    input  wire        start,
    output reg         busy,
    output reg         found,
    output reg  [7:0]  fs_error,
    output reg  [31:0] first_cluster,
    output reg  [31:0] file_size,
    output reg  [31:0] data_start_lba,
    output reg  [7:0]  sectors_per_cluster,
    // ????????????????????? sd_card_bmp ??? wav_sector_*???
    output reg         sd_req,
    output reg  [31:0] sd_lba,
    input  wire        sd_busy,
    input  wire        sd_valid,
    input  wire [7:0]  sd_byte,
    input  wire [8:0]  sd_byte_index,
    input  wire        sd_done,
    input  wire [7:0]  sd_error
);

    localparam [7:0] ERR_NONE     = 8'h00;
    localparam [7:0] ERR_SECTOR   = 8'h10;
    localparam [7:0] ERR_NOTFOUND = 8'h22;

        localparam [3:0] S_IDLE      = 4'd0,
                     S_BOOT      = 4'd1,
                     S_SETUP1    = 4'd2,
                     S_SETUP2    = 4'd3,
                     S_SETUP3    = 4'd4,
                     S_SETUP4    = 4'd5,
                     S_ROOT      = 4'd6,
                     S_NEXT      = 4'd7,
                     S_DONE      = 4'd8;


    reg [3:0]  state;
    reg        is_mbr;

    // BPB ??????
    reg [7:0]  bp_spc;
    reg [15:0] bp_reserved;
    reg [7:0]  bp_numfat;
    reg [15:0] bp_fatsz16;
    reg [31:0] bp_fatsz32;
    reg [31:0] bp_rootclus;
    reg [31:0] part_lba;

    // ?????? 32 ??????????????????
    reg [87:0] ent_name;      // 11 ???????????????????????????
    reg [15:0] ent_clus_hi;
    reg [15:0] ent_clus_lo;
    reg [31:0] ent_size;
    reg        ent_lfn, ent_dir, ent_del, ent_zero;
    reg        eval_pending;  // ???????????????????????????

    // ???????????????
    // ???????????? 100MHz ???????
    reg [31:0] fat_sz_r, base_r, numfat_r, spc_r, rootclus_r;
    reg [31:0] fat_area_r, meta_base_r, clus_off_r;
    reg [31:0] root_lba;
    reg [15:0] root_idx;
    reg [31:0] calc_data_start;

    function [7:0] uc;
        input [7:0] c;
        begin
            uc = ((c >= 8'h61) && (c <= 8'h7A)) ? (c - 8'h20) : c;
        end
    endfunction

    wire name_match = (MATCH_MODE == 1) ? (ent_name == TARGET_NAME)
                                        : (ent_name[23:0] == TARGET_NAME[23:0]); // ????????? WAV
    wire ent_ok     = !ent_lfn && !ent_dir && !ent_del && !ent_zero;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            state <= S_IDLE; busy <= 1'b0; found <= 1'b0; fs_error <= ERR_NONE;
            sd_req <= 1'b0; sd_lba <= 32'd0;
            is_mbr <= 1'b0; bp_spc <= 8'd0; bp_reserved <= 16'd0; bp_numfat <= 8'd0;
            bp_fatsz16 <= 16'd0; bp_fatsz32 <= 32'd0; bp_rootclus <= 32'd0; part_lba <= 32'd0;
            ent_name <= 88'd0; ent_clus_hi <= 16'd0; ent_clus_lo <= 16'd0; ent_size <= 32'd0;
            ent_lfn <= 1'b0; ent_dir <= 1'b0; ent_del <= 1'b0; ent_zero <= 1'b0;
            eval_pending <= 1'b0;
            root_lba <= 32'd0; root_idx <= 16'd0; calc_data_start <= 32'd0;
            first_cluster <= 32'd0; file_size <= 32'd0;
            data_start_lba <= 32'd0; sectors_per_cluster <= 8'd0;
        end else begin
            // ---------- ???????????????????????? sd_valid ?????????????????????----------
            if (state == S_ROOT && sd_valid) begin
                if (sd_byte_index[4:0] == 5'd0) begin
                    ent_lfn  <= (sd_byte == 8'h0F);
                    ent_zero <= (sd_byte == 8'h00);
                    ent_del  <= (sd_byte == 8'hE5);
                    ent_name <= 88'd0;
                end else if (sd_byte_index[4:0] < 5'd11) begin
                    ent_name <= {ent_name[79:0], uc(sd_byte)};
                end else if (sd_byte_index[4:0] == 5'd11) begin
                    ent_dir <= sd_byte[4];
                end else if (sd_byte_index[4:0] == 5'd20) begin
                    ent_clus_hi[7:0]   <= sd_byte;
                end else if (sd_byte_index[4:0] == 5'd21) begin
                    ent_clus_hi[15:8]  <= sd_byte;
                end else if (sd_byte_index[4:0] == 5'd26) begin
                    ent_clus_lo[7:0]   <= sd_byte;
                end else if (sd_byte_index[4:0] == 5'd27) begin
                    ent_clus_lo[15:8]  <= sd_byte;
                end else if (sd_byte_index[4:0] == 5'd28) begin
                    ent_size[7:0]      <= sd_byte;
                end else if (sd_byte_index[4:0] == 5'd29) begin
                    ent_size[15:8]     <= sd_byte;
                end else if (sd_byte_index[4:0] == 5'd30) begin
                    ent_size[23:16]    <= sd_byte;
                end else if (sd_byte_index[4:0] == 5'd31) begin
                    ent_size[31:24]    <= sd_byte;
                    eval_pending       <= 1'b1;      // ????????? -> ???????????????
                end
            end

            // ---------- ?????? BPB ?????? ----------
            if ((state == S_BOOT) && sd_valid) begin
                case (sd_byte_index)
                    9'd13: bp_spc            <= sd_byte;
                    9'd14: bp_reserved[7:0]  <= sd_byte;
                    9'd15: bp_reserved[15:8] <= sd_byte;
                    9'd16: bp_numfat         <= sd_byte;
                    9'd17: bp_fatsz16[7:0]   <= sd_byte;
                    9'd18: bp_fatsz16[15:8]  <= sd_byte;
                    9'd36: bp_fatsz32[7:0]   <= sd_byte;
                    9'd37: bp_fatsz32[15:8]  <= sd_byte;
                    9'd38: bp_fatsz32[23:16] <= sd_byte;
                    9'd39: bp_fatsz32[31:24] <= sd_byte;
                    9'd44: bp_rootclus[7:0]   <= sd_byte;
                    9'd45: bp_rootclus[15:8]  <= sd_byte;
                    9'd46: bp_rootclus[23:16] <= sd_byte;
                    9'd47: bp_rootclus[31:24] <= sd_byte;
                    // MBR ????????????????????? LBA ????????? 446+8 = 454
                    9'd454: part_lba[7:0]     <= sd_byte;
                    9'd455: part_lba[15:8]    <= sd_byte;
                    9'd456: part_lba[23:16]   <= sd_byte;
                    9'd457: part_lba[31:24]   <= sd_byte;
                    default: ;
                endcase
                // MBR ??????????????????? MBR ??? part_lba
                if (is_mbr) part_lba <= part_lba;
            end

            case (state)
            S_IDLE: if (start) begin
                busy <= 1'b1; found <= 1'b0; fs_error <= ERR_NONE;
                sd_req <= 1'b1; sd_lba <= 32'd0;
                state <= S_BOOT;
            end

            S_BOOT: begin
                if (sd_error != 8'd0) begin fs_error <= ERR_SECTOR; sd_req <= 1'b0; state <= S_DONE; end
                else if (sd_done) begin
                    sd_req <= 1'b0;
                    if (bp_spc == 8'd0) begin
                        // LBA0 ???????????? FAT32 ?????????????????? MBR ??????????????????
                        is_mbr <= 1'b1;
                        sd_req <= 1'b1;
                        sd_lba <= part_lba;
                        state  <= S_BOOT;                // ?????????????????????????????????
                    end else begin
                        state <= S_SETUP1;
                    end
                end
            end

                        // ---- ? 4 ?????????????/?????????? ----
            S_SETUP1: begin
                fat_sz_r   <= (bp_fatsz16 != 16'd0) ? {16'd0, bp_fatsz16} : bp_fatsz32;
                base_r     <= is_mbr ? part_lba : 32'd0;
                numfat_r   <= {24'd0, bp_numfat};
                spc_r      <= {24'd0, bp_spc};
                rootclus_r <= bp_rootclus;
                state      <= S_SETUP2;
            end

            S_SETUP2: begin
                fat_area_r <= numfat_r * fat_sz_r;
                state      <= S_SETUP3;
            end

            S_SETUP3: begin
                meta_base_r <= base_r + {16'd0, bp_reserved} + fat_area_r;
                clus_off_r  <= (rootclus_r - 32'd2) * spc_r;
                state       <= S_SETUP4;
            end

            S_SETUP4: begin
                data_start_lba      <= meta_base_r;
                root_lba            <= meta_base_r + clus_off_r;
                sectors_per_cluster <= bp_spc;
                sd_req <= 1'b1;
                sd_lba <= meta_base_r + clus_off_r;
                root_idx <= 16'd0;
                state <= S_ROOT;
            end
S_ROOT: begin
                if (sd_error != 8'd0) begin fs_error <= ERR_SECTOR; sd_req <= 1'b0; state <= S_DONE; end
                else if (eval_pending) begin
                    eval_pending <= 1'b0;
                    if (ent_ok && name_match) begin
                        first_cluster <= {ent_clus_hi, ent_clus_lo};
                        file_size     <= ent_size;
                        found         <= 1'b1;
                        state         <= S_NEXT;          // ????????????????????????
                    end else if (ent_zero) begin
                        fs_error <= ERR_NOTFOUND;
                        state    <= S_NEXT;
                    end
                end else if (sd_done) begin
                    sd_req <= 1'b0;
                    state  <= S_NEXT;
                end
            end

            S_NEXT: begin
                if (found) begin
                    state <= S_DONE;
                end else if (fs_error == ERR_NOTFOUND) begin
                    state <= S_DONE;
                end else if (root_idx + 16'd1 >= MAX_ROOT_SECTORS[15:0]) begin
                    fs_error <= ERR_NOTFOUND;
                    state    <= S_DONE;
                end else begin
                    root_idx <= root_idx + 16'd1;
                    sd_req <= 1'b1;
                    sd_lba <= root_lba + {16'd0, root_idx} + 32'd1;
                    state  <= S_ROOT;
                end
            end

            S_DONE: begin
                sd_req <= 1'b0;
                busy   <= 1'b0;
                if (!found && fs_error == ERR_NONE) fs_error <= ERR_NOTFOUND;
                state  <= S_IDLE;
            end
            default: state <= S_IDLE;
            endcase
        end
    end

endmodule
